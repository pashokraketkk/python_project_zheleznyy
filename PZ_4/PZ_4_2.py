#Дано число A (>1). Вывести наименьшее целое K, для которого сумма
# 1 + 1/2 + ... + 1/K будет больше A, и саму эту сумму.
while True:
    try:
        a = float(input("Введите число А (А > 1): "))
        if a > 1:
            break
        print("Число должно быть больше 1!")
    except ValueError:
        print("Неправильно ввели!")

#Добовляем слагаемые, пока сумма не привысит А
k = 0
s = 0
while s <= a:
    k += 1
    s += 1 / k

print("K =", k)
print("Сумма равна:", s)