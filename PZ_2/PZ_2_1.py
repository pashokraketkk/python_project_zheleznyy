#Даны целые положительные числа A и B, на отрезке длины А размещено максмально возможное кол-во отрезков длины В
while True:
    try:
        a = int(input("Введите число A: "))
        b = int(input("Введите число B: "))
        break
    except ValueError:
        print("Введите корректное число")

result = a // b
print("Количество отрезков:", result)